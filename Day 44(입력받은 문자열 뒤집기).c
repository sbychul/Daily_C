#include <stdio.h>

// 오늘의 문법 설명 : "두 개의 포인터(Two Pointers)"
// 문자열을 뒤집을 때 가장 효율적인 방법은 배열의 '시작'과 '끝'에 각각 포인터를 하나씩 두는 것입니다.

// 시작 포인터(start) : 첫 번째 문자를 가리키고 한 칸씩 뒤로 갑니다.
// 끝 포인터(end) : 마지막 문자를 가리키고 한 칸씩 앞으로 옵니다.
// 교환(Swap) : 두 포인터가 가리키는 문자를 서로 바꿉니다.
// 종료 조건 : 두 포인터가 서로 만나거나 교차하면 뒤집기가 끝납니다.

int main() {
	char str[100] = { 0 };
	printf("문자열을 입력하세요: ");
	scanf("%s", str);

	char* start = str;
	char* end = str;
	char temp = *start;

	while (*end != '\0') {
		end++;	// end를 마지막 문자 위치까지 보냄.
	}
	end--;		// 현재 \0 위치에 있는 상태. 한 칸 뒤로 보내기.

	printf("뒤집힌 결과: ");
	while (start < end) {
		temp = *start;	// 첫 값을 temp에 저장
		*start = *end;	// 끝 값을 start에 저장하여 값을 바꿈.
		*end = temp;	// 첫 값을 맨 뒤로 보냄.

		start++;		// start가 가르키는 주소를 다음 칸으로.
		end--;			// end가 가르키는 주소를 이전 칸으로.
	}
	printf("%s", str);

	return 0;
}


// printf("%s", temp); 가 0xc0000005 (세그폴트)를 일으킨 원인 :

// temp는 그냥 문자 하나(char)를 담는 작은 컵입니다.예를 들어 'A'가 들어있다면 컴퓨터 입장에서는 숫자 65입니다.
// 그런데 %s는 "주소(포인터)를 주면 거기로 가서 널 문자(\0)가 나올 때까지 다 읽어줄게!"라는 약속입니다.

// 즉, printf에게 숫자 65를 던져주며 % s로 읽으라고 하니,
