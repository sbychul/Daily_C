#include <stdio.h>
#include <stdlib.h>

int main() {
    int n = 0;
    printf("생성할 배열의 크기를 입력하세요: ");
    scanf("%d", &n);

    int* ptr = (int*)malloc(sizeof(int) * n); // 동적 할당 (Dynamic Array): "손님 오는 거 보고 차량 배차해." 3명이면 3칸, 1000명이면 1000칸. **메모리 낭비가 0(Zero)**입니다.

    for (int i = 0; i < n; i++) {
        printf("%d번째 정수 입력: ", i + 1);
        scanf("%d", &ptr[i]);
    }

    printf("\n[입력한 결과]\n");
    for (int i = 0; i < n; i++) {
        printf("%d ", ptr[i]);
    }

    free(ptr);
    printf("\n메모리가 해제되었습니다.");
    return 0;
}

//🧠 메모리 구조 시각화(한 번 더 확인!)
//지금 작성하신 코드가 실행될 때 메모리 안에서는 이런 일이 벌어집니다.
//
//스택(Stack) : ptr이라는 작은 쪽지(포인터 변수) 하나만 있습니다.
//힙(Heap) : 사용자가 입력한 n개만큼의 거대한 방이 만들어집니다.
//연결 : ptr이 힙에 있는 그 방의 시작 주소를 가리키고 있습니다.
//
//💡 딱 하나 더!(현업 개발자의 팁)
//지금 코드는 아주 짧아서 상관없지만, 나중에 코드가 길어지면 free를 한 직후에 습관처럼 해주는 행동이 하나 있습니다.
//
//free(ptr);  // 1. 방 뺐음 (반납)
//ptr = NULL; // 2. 주소록에서도 지워버림 (안전장치)
//
//이유: free(ptr)를 해도 ptr 변수 안에는 여전히 옛날 주소(예 : 0x5000)가 남아있습니다.
//실수로 나중에 ptr[0] = 5; 같은 코드를 쓰면, 이미 남의 땅이 된 곳을 건드려서 프로그램이 뻗어버릴 수 있습니다.
//이것을** 댕글링 포인터(Dangling Pointer)** 라고 부르는데, NULL로 초기화해두면 이런 실수를 막을 수 있습니다.