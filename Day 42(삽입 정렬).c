#include <stdio.h>

// 오늘의 문법 설명 : "손안의 카드를 정리하듯이"
// 삽입 정렬(Insertion Sort)은 우리가 카드를 손에 쥐고 정렬할 때와 가장 유사한 방식입니다.

// 원리 :
// 1. 두 번째 칸의 숫자부터 시작해서 앞쪽으로 이동하며 자리를 찾습니다.
// 2. "나보다 큰 녀석들은 오른쪽으로 한 칸씩 비켜!"라고 외치며 앞의 숫자들을 뒤로 밀어냅니다.
// 3. 나보다 작거나 같은 녀석을 만나면 바로 그 뒷자리에 쏙 삽입됩니다.
// 특징 : 이미 어느 정도 정렬이 되어 있는 상태라면 어떤 정렬보다도 빠릅니다. (베스트 케이스 $O(N)$)
// 하지만 역시나 평균적으로는 $O(N ^ 2)$의 시간 복잡도를 가집니다.

int main() {
	int arr[5] = { 50, 20, 40, 10, 30 };

	printf("[삽입 정렬 전 배열]\n");
	for (int i = 0; i < 5; i++) {
		printf("%d ", arr[i]);
	}

	for (int i = 1; i < 5; i++) {
		int key = arr[i];	// 두 번째 칸(arr[1])부터 시작.
		int j = i - 1;		// 나보다 큰 녀석들을 찾기 위한 변수. 첫 번째 칸(arr[0])부터 시작하기 위함.

		while (j >= 0 && arr[j] > key) {	// j가 0보다 크거나 같고, 새로 찾은 값이 처음 지정한 값보다 큰 동안 반복.
			arr[j + 1] = arr[j];			// 한 칸씩 오른쪽으로 복사(밀기)
			j--;							// j값을 줄여가며(key보다 왼쪽에 있는 정렬되지 않은 값을 찾기 위함. 작은 값이 왼쪽으로 가야 하니까) 계속 진행.
		}

		// 멈춘 자리(key보다 작으면 반복문이 멈춤) 바로 다음 칸에 key를 집어넣음. => key보다 작은 값 다음에 key가 와서 정렬됨.
		arr[j + 1] = key;
	}

	printf("\n\n[삽입 정렬 완료]\n");
	for (int i = 0; i < 5; i++) {
		printf("%d ", arr[i]);
	}
	return 0;
}

