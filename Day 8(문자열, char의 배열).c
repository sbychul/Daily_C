#include <stdio.h>
#include <string.h>
#include <ctype.h>

int main() {
    char word[21];
    int length = 0, i = 0;

    printf("영어 단어를 입력하세요 (최대 20자): ");
    scanf("%s", word);
    length = (int) strlen(word);

    printf("[변환 결과]\n대문자 역순: ");
    for (i = length - 1; i >= 0; i--) {
        printf("%c", toupper(word[i]));
    }
    printf("\n단어 길이: %d", length);
    return 0;
}

