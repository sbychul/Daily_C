#include <stdio.h>

void get_result(int a, int b, int *mok, int *nmg) {
    *mok = a / b;
    *nmg = a % b;
}

int main() {
    int num1 = 0, num2 = 0, q = 0, r = 0;

    printf("나눗셈할 두 정수를 입력하세요: ");
    scanf("%d %d", &num1, &num2);

    get_result(num1, num2, &q, &r);
    printf("[결과]: 몫: %d, 나머지: %d", q, r);

    return 0;
}

// &는 주소를 "알아내는" 녀석이고, * 는 주소를 타고 "찾아가는" 녀석입니다.
//
// 1. & (Ampersand) : "너 어디 살아?" (주소 추출)
// 변수 앞에 붙어서 * *그 변수의 실제 주소(방 번호) * *를 끄집어냅니다.
//
// 의미 : "Address of" (~의 주소)
// 역할 : 변수 num이 메모리 몇 번지에 살고 있는지 알아옴.
// 비유 : 친구에게 "너네 집 주소가 뭐야?"라고 묻는 것.
//
// int num = 10;
// // &num -> 0x1004 (메모리 주소가 튀어나옴)
//
// 2. * (Asterisk) : "그 주소로 돌격!" (접근 / 해제)
// 주소를 가지고 있는 변수(포인터) 앞에 붙어서, ** 그 주소로 순간 이동해서 값을 확인(또는 수정)** 합니다.이것을 어려운 말로** 역참조(Dereference)** 라고 합니다.
//
// 의미 : "Value at" (그 주소에 있는 값)
// 역할 : "0x1004번지로 가서 문 열고 안에 있는 거 가져와!"
// 비유 : 주소가 적힌 쪽지를 보고, 실제로 그 집 문을 열고 들어가는 행동.
//
// int* p = &num; // p는 0x1004라는 주소를 가짐
// // *p -> 10 (0x1004번지로 찾아가서 10을 가져옴)
//
//
// ⚠️ 주의 : *의 두 얼굴(가장 헷갈리는 점)
// * 기호는 쓰이는 위치에 따라 뜻이 완전히 다릅니다. 이것만 구분하면 됩니다!
//
// 1. 만들 때(선언) : "나 포인터야!" (신분증)자료형 뒤에 붙을 때는 "이 변수는 주소를 담는 변수입니다"라고 선언하는 것입니다. (아직 찾아가는 행동 아님)
// int* p; // 선언: "p는 앞으로 주소를 담을 거야."
//
// 2. 쓸 때(동작) : "찾아가자!" (행동개시)코드 실행 중에 변수 앞에 붙으면 "자, 이제 그 주소로 가보자!"라는 명령입니다.
// * p = 20; // 동작: "p가 가진 주소로 가서 20을 넣어라."