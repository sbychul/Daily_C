// 오늘의 핵심 요소(Spec)
// 포인터와 주소값 : 메모리 주소의 변화를 머릿속으로 그릴 수 있는가 ?
// Call by Value vs Call by Reference : 함수에 인자를 전달할 때 원본값이 변하는 원리를 아는가 ?
// 메모리 구조 : 스택(Stack)과 힙(Heap)의 차이를 명확히 구분하는가 ?

#include <stdio.h>

void swap(int* a, int* b) { // swap 함수 정의, 두 변수의 주소를 인자로 받을 예정
	// [리뷰어] 🚨 함정 발동: 값과 주소의 혼동!
		// 포인터 변수 a 앞에 *를 붙인 `*a`는 주소가 아니라 그 주소 안에 들어있는 '실제 정수값(10)'입니다.
		// 그런데 temp를 포인터(int*)로 선언해버리면, 컴퓨터는 "10이라는 숫자를 메모리 주소 10번지로 취급해라!"라고 오해하게 됩니다.
		// 값을 잠시 보관할 바구니는 일반 정수형 변수여야 합니다. 
		// 👉 수정: int temp = *a; 
	int* temp = *a; // 임시 변수에 a의 주소를 받아둠 

	*a = *b; // a에 b의 주소를 전달
	// [리뷰어] 아주 잘하셨습니다! a가 가리키는 공간에 b가 가리키는 공간의 '값(20)'을 덮어씌웁니다.

	*b = temp; // b에 temp의 주소를 전달. temp는 어차피 주소를 담은 변수기 때문에 *를 붙일 필요는 없음.
	// [리뷰어] 위에서 temp를 일반 int로 고쳤다면, 이 부분은 완벽하게 작동합니다! 
	// b가 가리키는 공간에 아까 피신시켜 둔 '값(10)'을 쏙 넣어주는 거죠.
}

// 포인터를 쓰지 않고 그냥 swap(int a, int b)를 했을 때 값이 바뀌지 않는 이유:
// 함수 내부에서 main() 내의 변수를 건드리려면 주소 값을 호출받아야 함.
// 메모리 주소 값을 전달(Call by Reference)받지 않고 x와 y의 값만을 전달(Call by Value)받는다면,
// swap 함수 내에서 값이 바뀔지는 몰라도, main 함수 내에 있던 x와 y에는 아무런 영향을 미치지 못함.
// Call by Value를 통해 값을 swap하고 이를 출력하고 싶다면 둘이 바뀐 값을 return하지 않는 이상, 해당 값을 main()에서 받아낼 수 없음.
// 바뀐 값을 return하더라도, main() 내의 변수에는 영향이 없다는 것은 동일.

int main() {
	int x = 10, y = 20;
	printf("[값 교환 전] x: %d, y: %d\n[swap 함수 실행 중..]\n", x, y);
	swap(&x, &y); // &를 통하여 함수에 x와 y의 주소를 전달. 이후 swap 함수 주석에 설명된 과정을 진행.
	printf("[값 교환 후] x: %d, y: %d", x, y);
	return 0; // 프로그램 정상 종료.
}