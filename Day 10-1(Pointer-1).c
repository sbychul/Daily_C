#include <stdio.h>

void swap(int* a, int* b) {
    int temp = *a;
    *a = *b;
    *b = temp;
}

int main() {
    int num1 = 10, num2 = 20;
    printf("[바꾸기 전] num1 = %d, num2 = %d\n", num1, num2);
    swap(&num1, &num2);
    printf("[바꾸기 후] num1 = %d, num2 = %d", num1, num2);
}

