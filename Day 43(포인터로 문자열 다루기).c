#include <stdio.h>

// 오늘의 문법 설명 : "문자열 상수의 정체"
// C언어에서 "Hello"라고 적는 문자열 상수는 메모리 어딘가에 저장된 첫 번째 문자의 '주소'를 의미합니다.

// 배열 방식(char str[]) : 문자열을 복사해서 내가 마음대로 바꿀 수 있는 '내 방'을 만드는 것과 같습니다.
// 포인터 방식(char* ptr) : 문자열이 저장된 '남의 집 주소'를 가리키는 것과 같습니다. (이 주소가 가리키는 내용은 읽기 전용이라 함부로 바꿀 수 없습니다.)
// NULL 문자(\0) : 문자열의 끝을 알리는 약속입니다.포인터로 문자열을 훑을 때 이 \0을 만날 때까지 반복하는 것이 핵심입니다.

int main() {
	char str[100] = { 0 };
	int length = 0;
	printf("문자열을 입력하세요: ");
	scanf("%s", str);

	char* ptr = str;
	while (*ptr != '\0') {
		length++;
		ptr++;
	}
	
	printf("문자열의 길이: %d", length);
	return 0;
}

