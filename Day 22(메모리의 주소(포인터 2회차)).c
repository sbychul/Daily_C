#include <stdio.h>
// 포인터 두 번 하는 게 이상한 거 아님, 다시 한 번 하자고 함

int main() {
	int num = 10;
	int *p = &num;
	// 포인터 변수(*) : 주소를 저장하는 전용 변수입니다.선언할 때 int* p; 처럼 타입 뒤에* 를 붙입니다.
	// 💡 추가 설명: 여기서 *는 "신분증" 같은 역할입니다. "나 p는 그냥 정수가 아니라, 주소를 담는 녀석이야!"라고 컴파일러에게 신원을 밝히는 기호죠.
	// 위 코드는 num의 주소(&num)을 저장하기 위해 포인터 변수를 사용(int* p)

	printf("[포인터 기초 테스트]\n1. num의 값: %d\n2. num의 주소: %p\n3. p가 가리키는 값: %d\n", num, p, *p);

	*p = 20;
	// 역참조 연산자(*) : 주소 앞에* 를 붙이면, ** "그 주소에 가서(간접 참조) 안에 있는 값을 가져와!" * *라는 뜻이 됩니다.
	// 💡 추가 설명: 여기서 *는 "열쇠" 또는 **"이동 버튼"**입니다. 주소(p)라는 문을 열고 들어가서 실제 내용물(num)을 만지게 해줍니다.
	// p는 주소가 들어가 있는 변수, 그 주소에 가서 안에 있는 값을 20으로 바꿔라 라는 뜻

	printf("\n[포인터를 통한 값 수정 완료]\n4. 수정된 num의 값: %d", num);
	return 0;
}

//	코드		/	상황			/		의미(번역)			/		비유
// int* p;	/ 만들 때(선언)	/ "나는 주소를 담는 변수야."	/ 신분증(Identity)
// *p = 20;	/ 쓸 때(동작)	/ "저 주소로 이동해!"		/ 텔레포트(Action)