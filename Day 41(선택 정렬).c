#include <stdio.h>

// 오늘의 문법 설명 : "최솟값 찾아서 멱살 잡기"
// 버블 정렬이 옆 친구와 계속 투닥거리며 자리를 바꿨다면, ** 선택 정렬(Selection Sort)** 은 아주 냉철한 정렬 방식입니다.

// 원리 :
// 배열 전체를 훑어서** 가장 작은 값(최솟값)** 이 어디 있는지 찾습니다.
// 그 최솟값을 찾아내면, 현재 정렬하려는 맨 앞의 숫자와 자리를 딱 한 번만 바꿉니다.
// 그다음 칸으로 이동해서 남은 숫자들 중 가장 작은 것을 찾아 또 자리를 바꿉니다.
// 장점: 버블 정렬에 비해 실제로 값을 바꾸는 횟수(Swap)가 적어 훨씬 효율적입니다. (물론 전체를 훑는 건 똑같아서 시간 복잡도는 $O(N ^ 2)$로 동일합니다.)

int main() {
	int temp = 0; // 우리의 "신" 임시 변수
	int arr[5] = { 50, 20, 40, 10, 30 };

	printf("[선택 정렬 전 배열]\n");
	for (int i = 0; i < 5; i++) {
		printf("%d ", arr[i]);
	}

	for (int i = 0; i < 5; i++) {
		// 숫자가 5개일 때, 바깥쪽 루프는 4번만 돌아도 됩니다. 왜냐하면 앞에서부터 4개의 숫자가 최솟값을 찾아 제자리에 앉고 나면,
		// 마지막 5번째 자리에 남은 숫자는 자동으로 제일 큰 숫자가 되기 때문에 굳이 한 번 더 검사할 필요가 없기 때문입니다.
		// (물론 5번 도는 유저님의 현재 코드도 안쪽 루프가 작동하지 않고 자기 자신과 스왑 후 넘어가기 때문에 결과에는 전혀 지장이 없습니다!)
		// ==> (int i = 0; i < 4; i++)
		int min_idx = i;
		for (int j = i + 1; j < 5; j++) {
			if (arr[j] < arr[min_idx]) { 
				min_idx = j; 
			}
		}
		
		temp = arr[i];
		arr[i] = arr[min_idx];
		arr[min_idx] = temp;
	}
	printf("\n\n[선택 정렬 완료]\n");
	for (int i = 0; i < 5; i++) {
		printf("%d ", arr[i]);
	}
	return 0;
}