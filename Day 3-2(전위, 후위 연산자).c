#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

int main() {
    int hp = 100;

    printf("=== Scene 1: 전위 연산자 (++hp) ===\n");
    // [미션 1] hp 앞에 ++를 붙여서 출력해보세요.
    // 예상: 101 출력
    printf("현재 체력: %d\n", ++hp);


    hp = 100; // 테스트를 위해 다시 100으로 리셋
    printf("\n=== Scene 2: 후위 연산자 (hp++) ===\n");

    // [미션 2] hp 뒤에 ++를 붙여서 출력해보세요.
    // 예상: 100 출력 (아직 안 올라간 것처럼 보임!)
    printf("현재 체력: %d\n", hp++);

    // [미션 3] 정말로 올라갔는지 그냥 hp를 출력해보세요.
    // 예상: 101 출력
    printf("다음 턴 체력: %d\n", hp);

    return 0;
}

