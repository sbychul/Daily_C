#include <stdio.h>

struct Character {
    char name[20];
    int level;
    float hp;
};

int main() {
    struct Character s1 = { 0 };
    printf("캐릭터 정보를 입력하세요.\n이름: ");
    scanf("%s", s1.name); // 문자열: 배열이기 때문에 주소를 찾아가라는 &가 필요하지 않음
    printf("레벨: ");
    scanf("%d", &s1.level); // 일반 정수 변수, 실수 변수이기 때문에 &가 필요
    printf("현재 체력: ");
    scanf("%f", &s1.hp);

    printf("[캐릭터 정보]\n이름: %s\n레벨: %d\n현재 체력: %.2f", s1.name, s1.level, s1.hp);
    return 0;
}

// 1. 원인 분석 : "4리터 물통에 8리터 물을 부었어요!"
// 코드에서 가장 중요한 불일치가 하나 있습니다.
//
// 구조체 선언 : float hp; (4바이트 크기의 실수)
// 입력 코드 : scanf("%lf", &s1.hp); (8바이트 크기의 double을 받겠다는 기호)
//
// C언어에서 scanf는 매우 엄격합니다.
// % f: float(4바이트) 전용
// % lf : double(8바이트) 전용
//
// 사용자 님은 4바이트짜리 방(hp) 을 만들어 놓고, 컴퓨터에게 "여기 8바이트(%lf)를 꽉 채워 넣어!" 라고 명령한 셈입니다.
//
// 2. "Stack around... corrupted" 경고창의 의미
// Visual Studio(Debug 모드)는 변수를 만들 때, 변수 주변에** "건드리면 안 되는 안전벽(Guard Byte)" * *을 몰래 세워둡니다.
//
// 입력 시도 : scanf가 hp 자리에 8바이트 데이터를 씁니다.
// 범람(Overflow) : 앞쪽 4바이트는 hp에 들어가지만, 남은 4바이트가 흘러넘쳐서 뒤에 있는 '안전벽'을 덮어써 버립니다.
// 검사 : main 함수가 끝나고(return 0) 퇴근하려는데, Visual Studio가 안전벽을 확인해보니 부서져 있는 것을 발견합니다.
// 경고 : "어? 누가 내 허락 없이 s1 변수 주변 메모리(스택)를 건드렸어! 이거 위험해!"라고 띄우는 것이 바로 저 창입니다.
//
//(출력 값이 0.00으로 나온 이유도, 8바이트 데이터를 억지로 4바이트 공간에 구겨 넣다 보니 비트 값이 꼬여서 엉뚱한 값(0에 가까운 값)이 저장되었기 때문입니다.)