#include <stdio.h>

// O(n) 달성하기 위한 2가지 힌트
// 이 바보 같은 중복 계산을 막고 O(n)의 속도(딱 n번만 계산)를 내려면, 뼈대를 살짝 뜯어고쳐야 합니다.
// 자료구조/알고리즘에서 주로 쓰이는 두 가지 마법의 스킬 중 하나를 선택해 보세요!


int fib(int n) // 원본
{
    if (n == 0) return 0;
    if (n == 1) return 1;
    return (fib(n - 1) + fib(n - 2));
}

// 루트 A. 메모이제이션 (Memoization - '메모장' 쓰기)
// 원리: 한 번 계산한 정답은 배열(메모장)에 적어둡니다.
// 함수가 호출되었을 때 가장 먼저 "혹시 이거 메모장에 있는 건가?" 확인하고, 있으면 계산 없이 바로 던져줍니다.
// 힌트: int memo[100] = {0}; 같은 배열을 하나 만들어두고 재귀 함수 안에서 활용해 보세요.
int memo[100] = { 0 }; // 전역 변수 메모장 형성. fibRoute1(n)의 값을 memo[n]의 값으로 저장할 계획.

int fibRoute1(int n) {
    if (n <= 1) { return n; } // 0과 1일 때는 해당 값 그대로 출력.
    if (memo[n] == 0) { // NULL이나 0이나 둘 다 비어 있음을 표현함.
        memo[n] = fibRoute1(n - 1) + fibRoute1(n - 2); // 메모장에 해당 값이 없을 때만 저장.
    }
    return memo[n];
}
// 왜 이 코드가 O(n)이 되었을까?
// 만약 fibRoute1(5)를 호출한다면, 처음 한 번만 바닥까지 파고 내려가면서 배열에[0, 1, 1, 2, 3, 5]를 순서대로 채워 넣습니다.
// 이후에 다른 쪽 가지에서 fibRoute1(3)이나 fibRoute1(2)를 또 부르게 되면,
// 컴퓨터는 재귀를 돌지 않고 memo 배열에 이미 적혀있는 정답을 0.001초 만에 쏙 빼서 돌려줍니다.즉, 정확히 n번의 덧셈만 일어나게 됩니다!


// 루트 B. 꼬리 재귀 (Tail Recursion - '바통' 넘겨주기)
// 원리: 함수가 자기를 다시 부를 때, 지금까지 더한 결괏값을 매개변수로 같이 던져주는 방식입니다.
// 힌트: 함수의 매개변수를 fib(int n, int a, int b) 처럼 3개로 늘려서, a에는 현재 항, b에는 다음 항을 넣고 릴레이 경주처럼 넘겨보세요.
int fibRoute2(int n, int a, int b) { // n == 남은 횟수, a == 더할 수 1(이전 수), b == 더할 수 2(다음 수)
    if (n == 0) { return a; } // 남은 횟수가 0, 이전 수 a를 그대로 반환. 더 더할 것 없음.
    return fibRoute2(n - 1, b, a + b); // 남은 횟수가 있음. a와 b를 더함.
}
// 이제 fibRoute2(5, 0, 1)을 넣으면 바통 터치가 어떻게 완벽하게 일어나는지 볼까요?
// (n = 5 남음) a = 0, b = 1 🏃‍♂️ 다음 주자에게 b(1)과 a + b(1)을 넘김
// (n = 4 남음) a = 1, b = 1 🏃‍♂️ 다음 주자에게 b(1)과 a + b(2)를 넘김
// (n = 3 남음) a = 1, b = 2 🏃‍♂️ 다음 주자에게 b(2)와 a + b(3)을 넘김
// (n = 2 남음) a = 2, b = 3 🏃‍♂️ 다음 주자에게 b(3)과 a + b(5)를 넘김
// (n = 1 남음) a = 3, b = 5 🏃‍♂️ 다음 주자에게 b(5)와 a + b(8)을 넘김
// (n = 0 도착!) 결승선 통과!현재 내 손(a)에 쥐고 있는 5를 그대로 반환!